-- Buyer sign-ups: the public "Join my buyers list" form at /buyers/.
-- A cash buyer fills in who they are and their buy box. The page is open to anyone, so nobody outside can read the
-- table: the form can only call buyer_signup(), which checks every field, refuses spam (a hidden field, too fast,
-- too many from one email or overall) and saves one row. Amr reads them in Admin > Logs > Buyer sign-ups, adds the
-- good ones to the Deal CRM's buyers (where they're encrypted with the team passphrase), then marks them added or
-- removes them. A sign-up stays here in plain text only until he handles it, so he removes it once it's in the CRM.
-- Safe to run more than once.
create table if not exists public.buyer_signups (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  company text,
  phone text not null,                                -- digits only
  email text not null,                                -- lower case
  kinds text[] not null default '{}',                 -- land, house
  states text[] not null default '{}',                -- two-letter codes, upper case
  areas text,                                         -- counties or cities as typed
  price_min numeric, price_max numeric,
  funding text check (funding in ('cash', 'hard_money', 'private', 'other')),
  close_days integer,                                 -- how fast they usually close
  per_year text,                                      -- how many deals a year, as picked
  notes text,
  texts_ok boolean not null default false,            -- agreed to deal alerts by text
  status text not null default 'new' check (status in ('new', 'added', 'not_a_fit'))
);
create index if not exists buyer_signups_new on public.buyer_signups (created_at desc) where status = 'new';
create index if not exists buyer_signups_email on public.buyer_signups (email, created_at desc);
alter table public.buyer_signups enable row level security;
revoke all on public.buyer_signups from anon, authenticated;

-- The form: anyone may call it. Returns true when saved. The started-at time and the hidden field are spam checks.
create or replace function public.buyer_signup(
  p_name text, p_company text, p_phone text, p_email text, p_kinds text[], p_states text[], p_areas text,
  p_price_min numeric, p_price_max numeric, p_funding text, p_close_days integer, p_per_year text, p_notes text,
  p_texts_ok boolean, p_started_at timestamptz, p_website text default null)
returns boolean language plpgsql security definer set search_path = '' as $$
declare
  v_phone text := public.dnc_normal(p_phone);
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_name text := left(btrim(coalesce(p_name, '')), 80);
begin
  -- spam: a filled hidden field, or sent less than 4 seconds after the page opened. Say yes and save nothing.
  if coalesce(btrim(p_website), '') <> '' or p_started_at is null or p_started_at > now() - interval '4 seconds' then return true; end if;
  if length(v_name) < 2 then raise exception 'Please add your name' using errcode = '22023'; end if;
  if length(v_phone) <> 10 then raise exception 'Please add a 10-digit US phone number' using errcode = '22023'; end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[a-z]{2,}$' or length(v_email) > 120 then raise exception 'Please check your email' using errcode = '22023'; end if;
  if p_price_min is not null and p_price_max is not null and p_price_min > p_price_max then raise exception 'The lowest price is above the highest' using errcode = '22023'; end if;
  -- too many: 3 a day from one email or phone, 40 an hour overall
  if (select count(*) from public.buyer_signups where (email = v_email or phone = v_phone) and created_at > now() - interval '1 day') >= 3
     or (select count(*) from public.buyer_signups where created_at > now() - interval '1 hour') >= 40 then
    raise exception 'We already have your details. Thank you!' using errcode = '22023';
  end if;
  insert into public.buyer_signups (name, company, phone, email, kinds, states, areas, price_min, price_max, funding, close_days, per_year, notes, texts_ok)
  values (
    v_name,
    nullif(left(btrim(coalesce(p_company, '')), 80), ''),
    v_phone, v_email,
    coalesce((select array_agg(distinct lower(btrim(k))) from unnest(p_kinds) k where lower(btrim(k)) in ('land', 'house')), '{}'),
    coalesce((select array_agg(distinct upper(btrim(s))) from unnest(p_states) s where btrim(s) ~* '^[a-z]{2}$'), '{}'),
    nullif(left(btrim(coalesce(p_areas, '')), 300), ''),
    case when p_price_min >= 0 and p_price_min < 100000000 then p_price_min end,
    case when p_price_max >= 0 and p_price_max < 100000000 then p_price_max end,
    case when p_funding in ('cash', 'hard_money', 'private', 'other') then p_funding end,
    case when p_close_days between 1 and 365 then p_close_days end,
    case when p_per_year in ('1-2', '3-5', '6-10', '10+') then p_per_year end,
    nullif(left(btrim(coalesce(p_notes, '')), 600), ''),
    coalesce(p_texts_ok, false)
  );
  return true;
end $$;

-- Amr: the sign-ups, newest first (new ones on top)
create or replace function public.portal_buyer_signups()
returns setof public.buyer_signups language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query select * from public.buyer_signups order by (status = 'new') desc, created_at desc;
end $$;

-- Amr: mark one added or not a fit, or remove it (p_status 'remove')
create or replace function public.buyer_signup_set(p_id bigint, p_status text)
returns boolean language plpgsql security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  if p_status = 'remove' then delete from public.buyer_signups where id = p_id; return found; end if;
  if p_status not in ('new', 'added', 'not_a_fit') then raise exception 'Unknown status' using errcode = '22023'; end if;
  update public.buyer_signups set status = p_status where id = p_id;
  return found;
end $$;

revoke all on function public.buyer_signup(text, text, text, text, text[], text[], text, numeric, numeric, text, integer, text, text, boolean, timestamptz, text) from public;
grant execute on function public.buyer_signup(text, text, text, text, text[], text[], text, numeric, numeric, text, integer, text, text, boolean, timestamptz, text) to anon, authenticated;
revoke all on function public.portal_buyer_signups(), public.buyer_signup_set(bigint, text) from public, anon;
grant execute on function public.portal_buyer_signups(), public.buyer_signup_set(bigint, text) to authenticated;
