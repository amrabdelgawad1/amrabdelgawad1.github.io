-- Phase 3: an onboarding checklist for every new hire: paperwork, tools, training and going live.
-- onboarding_items: the checklist (Amr edits it). An item is either ticked by Amr, or checked by the database from
-- what the person has really done ("auto"): signed in, Deal CRM on the team passphrase, course access, a roleplay
-- scored, a first shift, 50 dials, a real call scored. Auto items can't be ticked by hand.
-- onboarding_ticks: Amr's ticks, per person. Nothing private is ever stored here: "Payment details on file" is only a
-- tick; the details themselves stay outside the portal.
-- Who: Amr sees and ticks everyone's. Each person sees their own checklist (read only). Safe to run more than once.

create table if not exists public.onboarding_items (
  id bigint generated by default as identity primary key,
  grp text not null check (grp in ('Paperwork', 'Tools', 'Training', 'Going live')),
  title text not null check (char_length(btrim(title)) between 1 and 120),
  auto text check (auto in ('signed_in', 'code_set', 'crm_ready', 'course_access', 'roleplay_scored', 'first_shift', 'dials_50', 'real_scored')),
  sort integer not null default 100,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists onboarding_items_auto on public.onboarding_items (auto) where auto is not null;
alter table public.onboarding_items enable row level security;
revoke all on public.onboarding_items from anon, authenticated;
grant select, insert, update, delete on public.onboarding_items to authenticated;
grant usage on sequence public.onboarding_items_id_seq to authenticated;
drop policy if exists "onboarding items read" on public.onboarding_items;
create policy "onboarding items read" on public.onboarding_items for select to authenticated
  using (coalesce(public.is_tracker_admin(), false) or exists (select 1 from public.members m where m.user_id = auth.uid() and m.active));
drop policy if exists "onboarding items manage" on public.onboarding_items;
create policy "onboarding items manage" on public.onboarding_items for all to authenticated
  using (coalesce(public.is_tracker_admin(), false)) with check (coalesce(public.is_tracker_admin(), false));

create table if not exists public.onboarding_ticks (
  user_id uuid not null references auth.users(id) on delete cascade,
  item_id bigint not null references public.onboarding_items(id) on delete cascade,
  done_at timestamptz not null default now(),
  done_by uuid default auth.uid() references auth.users(id) on delete set null,
  primary key (user_id, item_id)
);
alter table public.onboarding_ticks enable row level security;
revoke all on public.onboarding_ticks from anon, authenticated;
grant select, insert, delete on public.onboarding_ticks to authenticated;
drop policy if exists "onboarding ticks read" on public.onboarding_ticks;
create policy "onboarding ticks read" on public.onboarding_ticks for select to authenticated
  using (user_id = auth.uid() or coalesce(public.is_tracker_admin(), false));
drop policy if exists "onboarding ticks manage" on public.onboarding_ticks;
create policy "onboarding ticks manage" on public.onboarding_ticks for all to authenticated
  using (coalesce(public.is_tracker_admin(), false)) with check (coalesce(public.is_tracker_admin(), false));

create or replace function public.onboarding_ticks_check()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if exists (select 1 from public.onboarding_items i where i.id = new.item_id and i.auto is not null) then
    raise exception 'This one ticks itself once it''s done.' using errcode = '22023';
  end if;
  if not exists (select 1 from public.members m where m.user_id = new.user_id) then
    raise exception 'Pick someone on the team.' using errcode = '22023';
  end if;
  new.done_at := now(); new.done_by := auth.uid();
  return new;
end $$;
revoke all on function public.onboarding_ticks_check() from public, anon, authenticated;
drop trigger if exists onboarding_ticks_check on public.onboarding_ticks;
create trigger onboarding_ticks_check before insert on public.onboarding_ticks for each row execute function public.onboarding_ticks_check();

-- Is an auto item done for this person?
create or replace function public.onboarding_auto(p_user uuid, p_key text)
returns boolean language sql stable security definer set search_path = '' as $$
  select case p_key
    when 'signed_in' then exists (select 1 from auth.users u where u.id = p_user and u.last_sign_in_at is not null)
    when 'code_set' then exists (select 1 from auth.mfa_factors f where f.user_id = p_user and f.status = 'verified')
    when 'crm_ready' then exists (select 1 from public.deal_logs l join public.deal_team t on t.only_one
                                   where l.user_id = p_user and l.tool = 'workspace' and l.blob ->> 'salt' = t.salt)
    when 'course_access' then exists (select 1 from public.members m where m.user_id = p_user and m.active
                                       and 'course' = any(public.portal_keys_of(m.role, m.access, m.not_given)))
    when 'roleplay_scored' then exists (select 1 from public.hub_uploads h where h.user_id = p_user and h.course = 'calls' and not h.real_call and h.score is not null)
    when 'first_shift' then exists (select 1 from public.shifts s where s.user_id = p_user and not s.owner)
    when 'dials_50' then coalesce((select sum(s.dials) from public.shifts s where s.user_id = p_user and not s.owner), 0) >= 50
    when 'real_scored' then exists (select 1 from public.hub_uploads h where h.user_id = p_user and h.course = 'calls' and h.real_call and h.score is not null)
    else false end
$$;
revoke all on function public.onboarding_auto(uuid, text) from public, anon, authenticated;

-- One person's checklist: Amr for anyone, everyone else only their own
create or replace function public.portal_onboarding(p_user uuid default null)
returns table(item_id bigint, grp text, title text, auto text, done boolean, done_at timestamptz)
language plpgsql stable security definer set search_path = '' as $$
declare v_user uuid := coalesce(p_user, auth.uid());
begin
  if v_user is null or (v_user is distinct from auth.uid() and not coalesce(public.is_tracker_admin(), false)) then
    raise exception 'Not allowed' using errcode = '42501';
  end if;
  return query
  select i.id, i.grp, i.title, i.auto,
         case when i.auto is not null then public.onboarding_auto(v_user, i.auto) else t.item_id is not null end,
         t.done_at
    from public.onboarding_items i
    left join public.onboarding_ticks t on t.item_id = i.id and t.user_id = v_user
   where i.active
   order by array_position(array['Paperwork', 'Tools', 'Training', 'Going live'], i.grp), i.sort, i.id;
end $$;
revoke all on function public.portal_onboarding(uuid) from public, anon;
grant execute on function public.portal_onboarding(uuid) to authenticated;

-- Amr: everyone's progress at a glance
create or replace function public.portal_onboarding_summary()
returns table(user_id uuid, name text, done integer, total integer, joined timestamptz)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query
  select m.user_id, m.name,
         (select count(*)::integer from public.onboarding_items i left join public.onboarding_ticks t on t.item_id = i.id and t.user_id = m.user_id
           where i.active and (case when i.auto is not null then public.onboarding_auto(m.user_id, i.auto) else t.item_id is not null end)),
         (select count(*)::integer from public.onboarding_items i where i.active),
         m.created_at
    from public.members m where m.active and m.user_id is not null
   order by m.created_at desc nulls last, m.name;
end $$;
revoke all on function public.portal_onboarding_summary() from public, anon;
grant execute on function public.portal_onboarding_summary() to authenticated;

