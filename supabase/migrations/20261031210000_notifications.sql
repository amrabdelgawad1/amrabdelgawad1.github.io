-- Phase 1: notifications. A bell in the top bar shows each person what needs them.
-- For Amr: course access requests, missed-shift requests, recordings and drills sent for review, a rep's deal changing
-- stage or getting a result, and problems or ideas reported. For reps: their missed-shift request decided, their
-- recording or drill reviewed. Payments are added once payments exist.
-- Only the database writes notifications (triggers and request_course_access), so nobody can fake one. Each person
-- reads only their own and can only mark them read. Text is short and never holds seller names, phones, addresses,
-- notes or anything encrypted: a deal is described by its kind, county and state only. Someone's own action never
-- notifies themselves. Notifications older than 90 days are cleared as new ones arrive. Safe to run more than once.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,   -- who it's for
  kind text not null check (kind in ('access_request', 'shift_request', 'shift_decided', 'review_sent', 'review_done', 'deal_stage', 'feedback', 'payment')),
  title text not null check (length(title) between 1 and 160),
  body text check (length(body) <= 300),
  link text check (link ~ '^/[^/\\]'),                                      -- a page on this site only
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists notifications_user on public.notifications (user_id, created_at desc);
create index if not exists notifications_unread on public.notifications (user_id) where read_at is null;
alter table public.notifications enable row level security;
revoke all on public.notifications from anon, authenticated;
grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;
drop policy if exists "notifications own read" on public.notifications;
create policy "notifications own read" on public.notifications for select to authenticated using (user_id = auth.uid());
drop policy if exists "notifications own mark" on public.notifications;
create policy "notifications own mark" on public.notifications for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

-- The one way in. Never callable from the page.
create or replace function public.notify(p_user uuid, p_kind text, p_title text, p_body text, p_link text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if p_user is null or p_user is not distinct from auth.uid() or nullif(btrim(coalesce(p_title, '')), '') is null then return; end if;   -- never yourself
  begin
    insert into public.notifications (user_id, kind, title, body, link)
    values (p_user, p_kind, left(p_title, 160), left(p_body, 300), case when p_link ~ '^/[^/\\]' then p_link end);
    delete from public.notifications n where n.user_id = p_user and n.created_at < now() - interval '90 days';
  exception when others then
    null;   -- a notification must never block the save that raised it
  end;
end $$;
revoke all on function public.notify(uuid, text, text, text, text) from public, anon, authenticated;

create or replace function public.notify_name(p_user uuid)
returns text language sql stable security definer set search_path = '' as $$
  select coalesce((select nullif(btrim(m.name), '') from public.members m where m.user_id = p_user), 'Someone')
$$;
revoke all on function public.notify_name(uuid) from public, anon, authenticated;

-- Mark everything read (the page marks single ones with a plain update on read_at)
create or replace function public.notifications_read_all()
returns integer language sql security definer set search_path = '' as $$
  with u as (update public.notifications set read_at = now() where user_id = auth.uid() and read_at is null returning 1)
  select count(*)::integer from u
$$;
revoke all on function public.notifications_read_all() from public, anon;
grant execute on function public.notifications_read_all() to authenticated;

-- A locked course: "Ask for access" sends Amr a notification. Once a day per course.
create or replace function public.request_course_access(p_course text)
returns text language plpgsql security definer set search_path = '' as $$
declare
  v_me uuid := auth.uid();
  v_owner uuid := public.portal_owner_id();
  v_name text;
  v_label text := case p_course when 'course' then 'Real Estate Acquisitions' when 'mkt' then 'Marketing' when 'psy' then 'Psychology and Therapy' end;
begin
  if v_me is null or not exists (select 1 from public.members m where m.user_id = v_me and m.active) then
    raise exception 'Not allowed' using errcode = '42501';
  end if;
  if v_label is null then raise exception 'Unknown course' using errcode = '22023'; end if;
  if v_owner is null then raise exception 'No one to ask yet' using errcode = '22023'; end if;
  if exists (select 1 from public.notifications n where n.user_id = v_owner and n.kind = 'access_request'
              and n.link = '/app/#people/' || v_me::text and n.body = v_label and n.created_at > now() - interval '1 day') then
    return 'already';
  end if;
  v_name := public.notify_name(v_me);
  perform public.notify(v_owner, 'access_request', v_name || ' asks for the ' || v_label || ' course', v_label, '/app/#people/' || v_me::text);
  return 'sent';
end $$;
revoke all on function public.request_course_access(text) from public, anon;
grant execute on function public.request_course_access(text) to authenticated;

-- Missed-shift requests: Amr hears about new ones, the rep hears the decision
create or replace function public.notify_shift_request()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_day text := to_char(new.shift_date, 'Mon DD');
begin
  if tg_op = 'INSERT' and new.status = 'pending' then
    perform public.notify(public.portal_owner_id(), 'shift_request', 'Missed-shift request from ' || public.notify_name(new.user_id),
      case when v_day is null then null else 'For ' || v_day end, '/app/#requests');
  elsif tg_op = 'UPDATE' and old.status = 'pending' and new.status in ('approved', 'rejected', 'declined') then
    perform public.notify(new.user_id, 'shift_decided', 'Your missed shift' || coalesce(' for ' || v_day, '') || ' was ' || case new.status when 'approved' then 'approved' else 'declined' end,
      nullif(left(btrim(coalesce(new.reason, '')), 300), ''), '/app/#track');
  end if;
  return null;
end $$;
revoke all on function public.notify_shift_request() from public, anon, authenticated;
drop trigger if exists notify_shift_request on public.shift_requests;
create trigger notify_shift_request after insert or update of status on public.shift_requests for each row execute function public.notify_shift_request();

-- Recordings and files sent to the Review center
create or replace function public.notify_hub_upload()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_course text := case new.course when 'acq' then 'Acquisitions' when 'mkt' then 'Marketing' when 'psy' then 'Psychology' else 'a course' end;
begin
  if tg_op = 'INSERT' and new.status = 'waiting' then
    perform public.notify(public.portal_owner_id(), 'review_sent', public.notify_name(new.user_id) || ' sent a ' || new.kind || ' to review',
      v_course || coalesce(' · ' || nullif(btrim(new.title), ''), ''), '/app/#review/' || new.user_id::text);
  elsif tg_op = 'UPDATE' and old.status = 'waiting' and new.status in ('approved', 'redo') then
    perform public.notify(new.user_id, 'review_done', 'Your ' || new.kind || ' was reviewed: ' || case new.status when 'approved' then 'approved' else 'please redo it' end,
      v_course || coalesce(' · ' || nullif(btrim(new.title), ''), ''), case new.course when 'acq' then '/course/' when 'mkt' then '/app/course/' else '/app/psychology/' end);
  end if;
  return null;
end $$;
revoke all on function public.notify_hub_upload() from public, anon, authenticated;
drop trigger if exists notify_hub_upload on public.hub_uploads;
create trigger notify_hub_upload after insert or update of status on public.hub_uploads for each row execute function public.notify_hub_upload();

-- Written drills in the Acquisitions course
create or replace function public.notify_course_submission()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.status = 'submitted' and (tg_op = 'INSERT' or old.status is distinct from 'submitted') then
    perform public.notify(public.portal_owner_id(), 'review_sent', public.notify_name(new.user_id) || ' sent a written drill',
      'Acquisitions · ' || new.module_id, '/course/#/admin');
  elsif tg_op = 'UPDATE' and old.status = 'submitted' and new.status in ('approved', 'needs_changes') then
    perform public.notify(new.user_id, 'review_done', 'Your written drill was ' || case new.status when 'approved' then 'approved' else 'sent back for changes' end,
      'Acquisitions · ' || new.module_id, '/course/');
  end if;
  return null;
end $$;
revoke all on function public.notify_course_submission() from public, anon, authenticated;
drop trigger if exists notify_course_submission on public.course_submissions;
create trigger notify_course_submission after insert or update of status on public.course_submissions for each row execute function public.notify_course_submission();

-- A rep's deal changing stage or getting a result (from deal_events): kind, county and state only
create or replace function public.notify_deal_event()
returns trigger language plpgsql security definer set search_path = '' as $$
declare d record; v_where text; v_what text;
begin
  if new.kind not in ('stage', 'result') or new.to_value is null then return null; end if;   -- a cleared result says nothing new
  if new.owner is not distinct from public.portal_owner_id() then return null; end if;          -- Amr's own deals never notify Amr
  select x.kind, x.county, x.state into d from public.deals x where x.id = new.deal_id;
  if not found then return null; end if;
  v_where := nullif(concat_ws(', ', initcap(d.county), d.state), '');
  v_what := case when new.kind = 'result' then
                   case new.to_value when 'sold' then 'sold' when 'assigned' then 'assigned' when 'kept' then 'kept' when 'passed' then 'passed' when 'elsewhere' then 'sold elsewhere' else new.to_value end
                 else 'moved to ' || case new.to_value when 'lead' then 'New lead' when 'talking' then 'Talking' when 'offer' then 'Offer sent'
                   when 'contract' then 'Under contract' when 'closed' then 'Closed' when 'passed' then 'Passed' else new.to_value end end;
  perform public.notify(public.portal_owner_id(), 'deal_stage', public.notify_name(new.owner) || '''s ' || coalesce(d.kind, 'deal') || ' deal ' || v_what,
    coalesce(v_where, 'No location yet'), '/app/deals/#id=' || new.deal_id);
  return null;
end $$;
revoke all on function public.notify_deal_event() from public, anon, authenticated;
drop trigger if exists notify_deal_event on public.deal_events;
create trigger notify_deal_event after insert on public.deal_events for each row execute function public.notify_deal_event();

-- Problems and ideas from the "Report a problem or idea" button
create or replace function public.notify_feedback()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  perform public.notify(public.portal_owner_id(), 'feedback', (case new.kind when 'problem' then 'Problem reported by ' else 'Idea from ' end) || public.notify_name(new.user_id),
    left(btrim(new.message), 140) || case when length(btrim(new.message)) > 140 then '…' else '' end, '/app/#logs');
  return null;
end $$;
revoke all on function public.notify_feedback() from public, anon, authenticated;
drop trigger if exists notify_feedback on public.feedback;
create trigger notify_feedback after insert on public.feedback for each row execute function public.notify_feedback();
