-- Phase 2: commissions. What each rep earned on a closed deal, owed or paid, feeding Cash.
-- Amr enters the numbers himself on a closed deal in the Deal CRM: the deal's profit and a percentage (the commission
-- is worked out from them), or the commission amount directly. Only a deal at Closed can get one.
-- Each commission is also an expense line in Cash (category "Commissions"), kept in step by the database: Paid in the
-- CRM is Paid in Cash, and ticking it paid in Cash marks the commission paid. A commission's Cash line can't be deleted
-- from Cash (remove the commission in the CRM instead), and its amount, date, type and category can't be changed there
-- (change it on the deal); ticking it paid there is fine. Its date in Cash: the day it was paid, or while owed, the day
-- the deal closed. The "closed" rule applies when a commission is added; a deal moved back from Closed later keeps it.
-- Kept as money history: removing the deal or the rep's account keeps the commission and its Cash line.
-- Who: only Amr reads or changes commissions. A rep sees only their own, through portal_my_commissions(): the deal
-- (kind, county, state), the amount, owed or paid and when. Never the profit or the percentage. Reps get a
-- notification when one is added and when it's paid. Safe to run more than once.

create table if not exists public.commissions (
  id bigint generated by default as identity primary key,
  deal_id text references public.deals(id) on delete set null,          -- kept if the deal is later removed
  deal_label text not null check (char_length(deal_label) between 1 and 120),   -- kind, county, state (set by the database)
  user_id uuid references auth.users(id) on delete set null,              -- the rep it's for (kept if their account is removed)
  rep_name text check (char_length(rep_name) <= 80),                     -- their name when it was added
  closed_on date,                                                         -- the deal's closing day when it was added
  profit numeric check (profit is null or (profit >= 0 and profit < 100000000)),
  percent numeric check (percent is null or (percent > 0 and percent <= 100)),
  amount numeric not null check (amount > 0 and amount < 10000000),
  status text not null default 'owed' check (status in ('owed', 'paid')),
  paid_on date,
  note text check (char_length(note) <= 300),
  cash_entry_id bigint references public.cash_entries(id) on delete set null,
  created_at timestamptz not null default now(),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  constraint commissions_paid_date check ((status = 'paid') = (paid_on is not null))
);
create unique index if not exists commissions_once on public.commissions (deal_id, user_id) where deal_id is not null;
create index if not exists commissions_user on public.commissions (user_id, created_at desc);
alter table public.commissions enable row level security;
revoke all on public.commissions from anon, authenticated;
grant select, insert, delete on public.commissions to authenticated;
grant update (profit, percent, amount, status, paid_on, note) on public.commissions to authenticated;
drop policy if exists "commissions owner" on public.commissions;
create policy "commissions owner" on public.commissions for all to authenticated
  using (coalesce(public.is_tracker_admin(), false)) with check (coalesce(public.is_tracker_admin(), false));

-- Checks, the amount from profit and percentage, the deal's label, and the Cash line
create or replace function public.commissions_check()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  d record; v_day date; v_today date := (now() at time zone 'Africa/Cairo')::date;
begin
  if tg_op = 'INSERT' then
    -- Amr only, before anything else (so nobody else learns anything from the messages below)
    if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
    select x.id, x.kind, x.county, x.state, x.stage, x.closed_on into d from public.deals x where x.id = new.deal_id;
    if not found then raise exception 'Save the deal first, then add its commission.' using errcode = '22023'; end if;
    if d.stage is distinct from 'closed' then
      raise exception 'Commissions count once the deal is closed. Mark it Closed and save, then add the commission.' using errcode = '22023';
    end if;
    if new.user_id is null or not exists (select 1 from public.members m where m.user_id = new.user_id) then
      raise exception 'Pick someone on the team.' using errcode = '22023';
    end if;
    new.deal_label := left(initcap(d.kind) || coalesce(', ' || nullif(concat_ws(', ', initcap(d.county), d.state), ''), ''), 120);
    new.rep_name := left(public.notify_name(new.user_id), 80);
    new.closed_on := d.closed_on;
    new.created_at := now(); new.created_by := auth.uid(); new.cash_entry_id := null;
  else
    -- cleared when the deal or the rep's account is removed, never moved to another
    new.deal_id := case when new.deal_id is null then null else old.deal_id end;
    new.user_id := case when new.user_id is null then null else old.user_id end;
    new.deal_label := old.deal_label; new.rep_name := old.rep_name; new.closed_on := old.closed_on;
    new.created_at := old.created_at; new.created_by := old.created_by; new.cash_entry_id := old.cash_entry_id;   -- only this trigger moves the link
    -- profit or percentage changed and the amount wasn't: work it out again
    if new.amount is not distinct from old.amount and (new.profit is distinct from old.profit or new.percent is distinct from old.percent) then
      new.amount := case when new.profit is not null and new.percent is not null then round(new.profit * new.percent / 100, 2) else old.amount end;
    end if;
  end if;
  -- the amount: typed, or worked out from the profit and the percentage
  if new.amount is null and new.profit is not null and new.percent is not null then
    new.amount := round(new.profit * new.percent / 100, 2);
  end if;
  if new.amount is null or new.amount <= 0 then
    raise exception 'Enter the commission, or the profit and a percentage.' using errcode = '22023';
  end if;
  new.amount := round(new.amount, 2);
  new.note := nullif(btrim(coalesce(new.note, '')), '');
  if new.status = 'paid' then new.paid_on := coalesce(new.paid_on, v_today); else new.paid_on := null; end if;
  if new.paid_on > v_today + 1 then raise exception 'The paid date can''t be in the future.' using errcode = '22023'; end if;

  -- the Cash line (an expense), kept in step. Its date: the day it was paid, or while owed, the day the deal closed.
  v_day := coalesce(new.paid_on, new.closed_on, (new.created_at at time zone 'Africa/Cairo')::date, v_today);
  perform set_config('portal.commission_sync', 'on', true);
  if new.cash_entry_id is not null and exists (select 1 from public.cash_entries c where c.id = new.cash_entry_id) then
    update public.cash_entries c set kind = 'expense', entry_date = v_day, category = 'Commissions', amount = new.amount,
        settled = new.status = 'paid', recurring = false, currency = 'USD', fx_rate = null,
        settled_at = case when new.status = 'paid' then coalesce(case when c.settled then c.settled_at end, (new.paid_on::timestamp at time zone 'Africa/Cairo') + interval '12 hours') end,
        note = left(new.deal_label || coalesce(' · ' || new.note, ''), 300)
     where c.id = new.cash_entry_id;
  else
    insert into public.cash_entries (kind, entry_date, title, party, category, amount, settled, settled_at, note, currency, recurring)
    values ('expense', v_day, left('Commission: ' || coalesce(new.rep_name, 'Someone'), 120), left(coalesce(new.rep_name, 'Someone'), 80), 'Commissions', new.amount, new.status = 'paid',
            case when new.status = 'paid' then (new.paid_on::timestamp at time zone 'Africa/Cairo') + interval '12 hours' end,
            left(new.deal_label || coalesce(' · ' || new.note, ''), 300), 'USD', false)
    returning id into new.cash_entry_id;
  end if;
  perform set_config('portal.commission_sync', '', true);
  return new;
end $$;
revoke all on function public.commissions_check() from public, anon, authenticated;
drop trigger if exists commissions_check on public.commissions;
create trigger commissions_check before insert or update on public.commissions for each row execute function public.commissions_check();

-- Tell the rep: added, and paid
create or replace function public.commissions_notify()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_amt text := '$' || to_char(new.amount, 'FM999,999,990.00');
begin
  if tg_op = 'INSERT' then
    perform public.notify(new.user_id, 'payment', 'Commission added: ' || v_amt || case when new.status = 'paid' then ' (paid)' else '' end, new.deal_label, '/app/#home');
  elsif old.status = 'owed' and new.status = 'paid' then
    perform public.notify(new.user_id, 'payment', 'Your commission of ' || v_amt || ' was paid', new.deal_label, '/app/#home');
  end if;
  return null;
end $$;
revoke all on function public.commissions_notify() from public, anon, authenticated;
drop trigger if exists commissions_notify on public.commissions;
create trigger commissions_notify after insert or update of status on public.commissions for each row execute function public.commissions_notify();

-- Removing a commission removes its Cash line
create or replace function public.commissions_gone()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if old.cash_entry_id is not null then
    perform set_config('portal.commission_sync', 'on', true);
    delete from public.cash_entries c where c.id = old.cash_entry_id;
    perform set_config('portal.commission_sync', '', true);
  end if;
  return null;
end $$;
revoke all on function public.commissions_gone() from public, anon, authenticated;
drop trigger if exists commissions_gone on public.commissions;
create trigger commissions_gone after delete on public.commissions for each row execute function public.commissions_gone();

-- In Cash: a commission's line can't be deleted there, and ticking it paid (or not) there updates the commission
create or replace function public.cash_commission_guard()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(current_setting('portal.commission_sync', true), '') = 'on' then return old; end if;
  if exists (select 1 from public.commissions k where k.cash_entry_id = old.id) then
    raise exception 'This is a commission. Remove it in the Deal CRM, on the deal.' using errcode = '22023';
  end if;
  return old;
end $$;
revoke all on function public.cash_commission_guard() from public, anon, authenticated;
drop trigger if exists cash_commission_guard on public.cash_entries;
create trigger cash_commission_guard before delete on public.cash_entries for each row execute function public.cash_commission_guard();

create or replace function public.cash_commission_edit()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(current_setting('portal.commission_sync', true), '') = 'on' then return new; end if;
  if exists (select 1 from public.commissions k where k.cash_entry_id = old.id)
     and (new.kind, new.amount, new.currency, new.fx_rate, new.category, new.entry_date, new.recurring)
         is distinct from (old.kind, old.amount, old.currency, old.fx_rate, old.category, old.entry_date, old.recurring) then
    raise exception 'This is a commission. Change its amount on the deal in the Deal CRM; here you can only tick it paid.' using errcode = '22023';
  end if;
  return new;
end $$;
revoke all on function public.cash_commission_edit() from public, anon, authenticated;
drop trigger if exists cash_commission_edit on public.cash_entries;
create trigger cash_commission_edit before update on public.cash_entries for each row execute function public.cash_commission_edit();

create or replace function public.cash_commission_paid()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if pg_trigger_depth() > 1 or old.settled is not distinct from new.settled then return null; end if;
  update public.commissions k set status = case when new.settled then 'paid' else 'owed' end,
      paid_on = case when new.settled then coalesce((new.settled_at at time zone 'Africa/Cairo')::date, (now() at time zone 'Africa/Cairo')::date) end
   where k.cash_entry_id = new.id and k.status is distinct from case when new.settled then 'paid' else 'owed' end;
  return null;
end $$;
revoke all on function public.cash_commission_paid() from public, anon, authenticated;
drop trigger if exists cash_commission_paid on public.cash_entries;
create trigger cash_commission_paid after update of settled on public.cash_entries for each row execute function public.cash_commission_paid();

-- A rep's own commissions (never the profit or the percentage)
create or replace function public.portal_my_commissions()
returns table(id bigint, deal_label text, amount numeric, status text, paid_on date, created_at timestamptz)
language sql stable security definer set search_path = '' as $$
  select k.id, k.deal_label, k.amount, k.status, k.paid_on, k.created_at
    from public.commissions k where k.user_id = auth.uid()
   order by (k.status = 'paid'), k.created_at desc
   limit 200
$$;
revoke all on function public.portal_my_commissions() from public, anon;
grant execute on function public.portal_my_commissions() to authenticated;
