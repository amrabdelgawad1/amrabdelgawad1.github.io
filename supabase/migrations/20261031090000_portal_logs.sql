-- 3. What shipped
-- ---------------------------------------------------------------------------------------------------------------
create table if not exists public.change_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  title text not null,
  detail text,
  sql_ran text,              -- migration file names, or "none"
  link text                  -- the pull request
);
alter table public.change_log enable row level security;
revoke all on public.change_log from anon, authenticated;

create or replace function public.log_change(p_title text, p_detail text default null, p_sql text default null, p_link text default null)
returns bigint language plpgsql security definer set search_path = '' as $$
declare v_id bigint;
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  insert into public.change_log (title, detail, sql_ran, link) values (p_title, p_detail, p_sql, p_link) returning id into v_id;
  return v_id;
end $$;
revoke all on function public.log_change(text, text, text, text) from public, anon;
grant execute on function public.log_change(text, text, text, text) to authenticated;

