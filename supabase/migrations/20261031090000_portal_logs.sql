-- Phase 0: logs. Three things Amr can read in /app > Logs, nobody else:
--   1. app_errors: errors the signed-in pages hit in people's browsers (portal-shell.js reports them). Capped per
--      person per hour, trimmed, never anything typed into a form.
--   2. activity_events: key actions written by triggers (a Deal CRM save, a shift request decided, a recording or drill
--      sent). Never deal contents, never hours or pay. portal_activity() adds sign-ins (Supabase's own auth log) and
--      role and access changes (access_log) to the same list.
--   3. change_log: what shipped and what database changes ran, one line per release. Amr (or the builder, through the
--      SQL editor) adds lines; the page lists them.
-- Safe to run more than once.

-- ---------------------------------------------------------------------------------------------------------------
-- 1. Errors from the browser
-- ---------------------------------------------------------------------------------------------------------------
create table if not exists public.app_errors (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  user_id uuid default auth.uid(),
  page text, message text not null, source text, line integer, stack text, ua text
);
create index if not exists app_errors_at on public.app_errors (at desc);
alter table public.app_errors enable row level security;
revoke all on public.app_errors from anon, authenticated;

-- Signed-in pages call this; it trims everything and keeps at most 30 errors per person per hour
create or replace function public.log_app_error(p_page text, p_message text, p_source text default null, p_line integer default null,
                                                p_stack text default null, p_ua text default null)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null or coalesce(btrim(p_message), '') = '' then return; end if;
  if (select count(*) from public.app_errors where user_id = auth.uid() and at > now() - interval '1 hour') >= 30 then return; end if;
  insert into public.app_errors (user_id, page, message, source, line, stack, ua)
  values (auth.uid(), left(p_page, 300), left(p_message, 500), left(p_source, 300), p_line, left(p_stack, 2000), left(p_ua, 300));
end $$;
revoke all on function public.log_app_error(text, text, text, integer, text, text) from public, anon;
grant execute on function public.log_app_error(text, text, text, integer, text, text) to authenticated;

-- ---------------------------------------------------------------------------------------------------------------
-- 2. Activity: key actions, written by triggers
-- ---------------------------------------------------------------------------------------------------------------
create table if not exists public.activity_events (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  actor uuid,
  kind text not null,        -- deal_saved | request_decided | drill_sent
  target uuid,               -- whose thing it was (the holder, the requester)
  detail text                -- short, never contents: "workspace", "approved", "mkt"
);
create index if not exists activity_events_at on public.activity_events (at desc);
alter table public.activity_events enable row level security;
revoke all on public.activity_events from anon, authenticated;

create or replace function public.activity_note()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_actor uuid := auth.uid();
begin
  if tg_table_name = 'deal_logs' then
    -- the CRM saves often: one line per person and row per 15 minutes is enough
    if exists (select 1 from public.activity_events e where e.kind = 'deal_saved' and e.actor is not distinct from v_actor
                and e.target = new.user_id and e.detail = new.tool and e.at > now() - interval '15 minutes') then return new; end if;
    insert into public.activity_events (actor, kind, target, detail) values (v_actor, 'deal_saved', new.user_id, new.tool);
  elsif tg_table_name = 'shift_requests' then
    if new.status is distinct from old.status and new.status <> 'pending' then
      insert into public.activity_events (actor, kind, target, detail) values (v_actor, 'request_decided', new.user_id, new.status);
    end if;
  elsif tg_table_name = 'hub_uploads' then
    insert into public.activity_events (actor, kind, target, detail) values (v_actor, 'drill_sent', new.user_id, coalesce(new.course, '') || ' ' || coalesce(new.kind, ''));
  end if;
  return new;
exception when others then
  return new;   -- a log line must never block the real save
end $$;
revoke all on function public.activity_note() from public, anon, authenticated;

drop trigger if exists activity_deal_saved on public.deal_logs;
create trigger activity_deal_saved after insert or update of blob on public.deal_logs for each row execute function public.activity_note();
drop trigger if exists activity_request_decided on public.shift_requests;
create trigger activity_request_decided after update of status on public.shift_requests for each row execute function public.activity_note();
drop trigger if exists activity_drill_sent on public.hub_uploads;
create trigger activity_drill_sent after insert on public.hub_uploads for each row execute function public.activity_note();

