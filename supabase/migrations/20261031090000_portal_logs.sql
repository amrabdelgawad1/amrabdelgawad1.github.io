create or replace function public.portal_errors(p_days integer default 7)
returns table(at timestamptz, who text, page text, message text, source text, line integer, ua text)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query
  select e.at, coalesce(m.name, case when e.user_id = public.portal_owner_id() then 'Amr' end, 'Someone'), e.page, e.message, e.source, e.line, e.ua
    from public.app_errors e left join public.members m on m.user_id = e.user_id
   where e.at > now() - make_interval(days => greatest(1, least(p_days, 90)))
   order by e.at desc limit 300;
end $$;

-- Sign-ins come from Supabase's own auth log, when the project keeps it in the database (empty list otherwise)
create or replace function public.portal_signins(p_since timestamptz)
returns table(at timestamptz, actor uuid)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query select l.created_at, nullif(l.payload ->> 'actor_id', '')::uuid
                 from auth.audit_log_entries l where l.created_at > p_since and l.payload ->> 'action' = 'login';
exception when others then
  return;
end $$;

create or replace function public.portal_activity(p_days integer default 7)
returns table(at timestamptz, who text, kind text, detail text)
language plpgsql stable security definer set search_path = '' as $$
declare v_since timestamptz := now() - make_interval(days => greatest(1, least(p_days, 90)));
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query
  with x as (
    select e.at, e.actor, e.target, e.kind, e.detail from public.activity_events e where e.at > v_since
    union all
    select a.at, a.actor, a.target, 'access_changed', left(a.change::text, 200) from public.access_log a where a.at > v_since
    union all
    select s.at, s.actor, null::uuid, 'signed_in', null::text from public.portal_signins(v_since) s
  )
  select x.at,
         coalesce(m.name, case when x.actor = public.portal_owner_id() then 'Amr' end, case when x.actor is null then 'The system' end, 'Someone'),
         x.kind,
         case when x.target is not null and x.target is distinct from x.actor
              then coalesce(t.name, case when x.target = public.portal_owner_id() then 'Amr' end, 'someone') || coalesce(': ' || x.detail, '')
              else x.detail end
    from x
    left join public.members m on m.user_id = x.actor
    left join public.members t on t.user_id = x.target
   order by x.at desc limit 400;
end $$;

create or replace function public.portal_changes()
returns table(at timestamptz, title text, detail text, sql_ran text, link text)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query select c.at, c.title, c.detail, c.sql_ran, c.link from public.change_log c order by c.at desc limit 300;
end $$;

revoke all on function public.portal_errors(integer), public.portal_signins(timestamptz), public.portal_activity(integer), public.portal_changes() from public, anon;
grant execute on function public.portal_errors(integer), public.portal_signins(timestamptz), public.portal_activity(integer), public.portal_changes() to authenticated;
