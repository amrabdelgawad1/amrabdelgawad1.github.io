-- Getting people to use the portal (blueprint): a "Report a problem or idea" button on every page, and one pinned
-- announcement from Amr on everyone's Team home.
-- Safe to run more than once.

-- ---------- feedback ----------
create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  user_id uuid default auth.uid(),
  kind text not null check (kind in ('problem', 'idea')),
  page text,
  message text not null,
  done boolean not null default false
);
alter table public.feedback enable row level security;
revoke all on public.feedback from anon, authenticated;

-- Anyone signed in on the team (or Amr, or later a student) can send; at most 20 a day each
create or replace function public.send_feedback(p_kind text, p_message text, p_page text default null)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'Not allowed' using errcode = '42501'; end if;
  if coalesce(btrim(p_message), '') = '' then raise exception 'Write something first' using errcode = '22023'; end if;
  if (select count(*) from public.feedback where user_id = auth.uid() and at > now() - interval '1 day') >= 20 then
    raise exception 'That''s a lot for one day. Send the rest tomorrow.' using errcode = '22023';
  end if;
  insert into public.feedback (kind, message, page) values (case when p_kind = 'idea' then 'idea' else 'problem' end, left(btrim(p_message), 2000), left(p_page, 300));
end $$;

create or replace function public.portal_feedback(p_days integer default 30)
returns table(id bigint, at timestamptz, who text, kind text, page text, message text, done boolean)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query select f.id, f.at, coalesce(m.name, case when f.user_id = public.portal_owner_id() then 'Amr' end, 'Someone'), f.kind, f.page, f.message, f.done
    from public.feedback f left join public.members m on m.user_id = f.user_id
   where f.at > now() - make_interval(days => greatest(1, least(p_days, 365))) order by f.done, f.at desc limit 300;
end $$;

create or replace function public.feedback_done(p_id bigint, p_done boolean default true)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  update public.feedback set done = p_done where id = p_id;
end $$;

-- ---------- one pinned announcement ----------
create table if not exists public.announcement (
  only_one boolean primary key default true check (only_one),
  message text not null,
  updated_at timestamptz not null default now()
);
alter table public.announcement enable row level security;
revoke all on public.announcement from anon, authenticated;

-- What the Team home shows (active team members and Amr); null when there's none
create or replace function public.portal_announcement()
returns jsonb language sql stable security definer set search_path = '' as $$
  select case when coalesce(public.is_tracker_admin(), false) or exists (select 1 from public.members m where m.user_id = auth.uid() and m.active)
    then (select jsonb_build_object('message', a.message, 'updated_at', a.updated_at) from public.announcement a where a.only_one) end
$$;

-- Amr posts it, or clears it with an empty message
create or replace function public.set_announcement(p_message text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  if coalesce(btrim(p_message), '') = '' then delete from public.announcement; return; end if;
  insert into public.announcement (only_one, message, updated_at) values (true, left(btrim(p_message), 600), now())
    on conflict (only_one) do update set message = excluded.message, updated_at = now();
end $$;

revoke all on function public.send_feedback(text, text, text), public.portal_feedback(integer), public.feedback_done(bigint, boolean),
  public.portal_announcement(), public.set_announcement(text) from public, anon;
grant execute on function public.send_feedback(text, text, text), public.portal_feedback(integer), public.feedback_done(bigint, boolean),
  public.portal_announcement(), public.set_announcement(text) to authenticated;
