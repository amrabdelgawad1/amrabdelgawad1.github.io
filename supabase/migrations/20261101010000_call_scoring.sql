-- Phase 3: call scoring and roleplay practice.
-- Reps send a call for scoring from the app, not only from inside a course: a real seller call (everyone on it agreed
-- to be recorded) or a roleplay against one of Amr's practice scenarios. It goes to the Review center like any other
-- recording, as course "calls", and Amr scores it on the same 50-point scorecard (hub_review). Each rep sees their own
-- scores over time; Amr sees everyone's.
-- roleplay_scenarios: Amr writes them (the seller, what the rep knows, the goal, and notes only for the person playing
-- the seller). Team members read the active ones. Safe to run more than once.

create table if not exists public.roleplay_scenarios (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 100),
  kind text not null default 'land' check (kind in ('land', 'house')),
  level text not null default 'medium' check (level in ('easy', 'medium', 'hard')),
  seller text not null default '' check (char_length(seller) <= 400),    -- who the rep is calling
  know text not null default '' check (char_length(know) <= 1200),      -- what the rep knows before dialing
  goal text not null default '' check (char_length(goal) <= 400),       -- what a good call ends with
  hidden text not null default '' check (char_length(hidden) <= 1500),  -- only for the person playing the seller
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.roleplay_scenarios enable row level security;
revoke all on public.roleplay_scenarios from anon, authenticated;
grant select, insert, update, delete on public.roleplay_scenarios to authenticated;
grant usage on sequence public.roleplay_scenarios_id_seq to authenticated;

-- Who may send a call for scoring: Amr, and the calling team (people with Deal tools; not learners only)
create or replace function public.calls_can_send()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.portal_can('deals'), false)
$$;
revoke all on function public.calls_can_send() from public, anon;
grant execute on function public.calls_can_send() to authenticated;

drop policy if exists "scenarios read" on public.roleplay_scenarios;
create policy "scenarios read" on public.roleplay_scenarios for select to authenticated
  using (coalesce(public.is_tracker_admin(), false) or (active and public.calls_can_send()));
drop policy if exists "scenarios manage" on public.roleplay_scenarios;
create policy "scenarios manage" on public.roleplay_scenarios for all to authenticated
  using (coalesce(public.is_tracker_admin(), false)) with check (coalesce(public.is_tracker_admin(), false));
create or replace function public.roleplay_scenarios_stamp()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  if tg_op = 'INSERT' then new.created_at := now(); else new.created_at := old.created_at; end if;
  return new;
end $$;
drop trigger if exists roleplay_scenarios_stamp on public.roleplay_scenarios;
create trigger roleplay_scenarios_stamp before insert or update on public.roleplay_scenarios for each row execute function public.roleplay_scenarios_stamp();

-- Uploads: a new course "calls", and which scenario a roleplay was for
alter table public.hub_uploads drop constraint if exists hub_uploads_course_check;
alter table public.hub_uploads add constraint hub_uploads_course_check check (course in ('acq', 'mkt', 'psy', 'calls'));
alter table public.hub_uploads add column if not exists scenario_id bigint references public.roleplay_scenarios(id) on delete set null;
alter table public.hub_uploads drop constraint if exists hub_uploads_scenario;
alter table public.hub_uploads add constraint hub_uploads_scenario check (scenario_id is null or (course = 'calls' and not real_call));

create or replace function public.hub_can_send(p_course text)
returns boolean language sql stable security definer set search_path = public, pg_temp as $$
  select case p_course
    when 'acq' then public.portal_can('course')
    when 'mkt' then public.learn_can_open('mkt')
    when 'psy' then public.learn_can_open('psy')
    when 'calls' then public.calls_can_send()
    else false end
$$;
revoke all on function public.hub_can_send(text) from public;
grant execute on function public.hub_can_send(text) to authenticated;

-- Notifications: name the new kind, and send the rep back to Call scoring
create or replace function public.notify_hub_upload()
returns trigger language plpgsql security definer set search_path = '' as $$
declare v_course text := case new.course when 'acq' then 'Acquisitions' when 'mkt' then 'Marketing' when 'psy' then 'Psychology'
                                          when 'calls' then case when new.real_call then 'Real call' else 'Roleplay' end else 'a course' end;
begin
  if tg_op = 'INSERT' and new.status = 'waiting' then
    perform public.notify(public.portal_owner_id(), 'review_sent', public.notify_name(new.user_id) || ' sent a ' || case when new.course = 'calls' then 'call to score' else new.kind || ' to review' end,
      v_course || coalesce(' · ' || nullif(btrim(new.title), ''), ''), '/app/#review/' || new.user_id::text);
  elsif tg_op = 'UPDATE' and old.status = 'waiting' and new.status in ('approved', 'redo') then
    perform public.notify(new.user_id, 'review_done',
      case when new.course = 'calls' and new.score is not null then 'Your call was scored: ' || (new.score ->> 'total') || ' of 50'
           else 'Your ' || new.kind || ' was reviewed: ' || case new.status when 'approved' then 'approved' else 'please redo it' end end,
      v_course || coalesce(' · ' || nullif(btrim(new.title), ''), ''),
      case new.course when 'acq' then '/course/' when 'mkt' then '/app/course/' when 'calls' then '/app/#scoring' else '/app/psychology/' end);
  end if;
  return null;
end $$;
revoke all on function public.notify_hub_upload() from public, anon, authenticated;
