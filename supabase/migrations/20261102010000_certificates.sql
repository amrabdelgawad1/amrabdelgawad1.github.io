-- Phase 3: course certificates for the Acquisitions course (Module 20).
-- certificates: one row per certificate Amr issues. The name printed is typed by Amr when he issues it. Each one has a
-- random code (ACQ-XXXXX-XXXXX) for a public check page (/cert/?c=CODE): anyone with the code sees the name, the
-- course, the dates and whether it's current, and nothing else. A certificate is valid for one year; renewing it
-- (one new call 40+ and the law-changes quiz, Lesson 20.1) adds a year. Revoking keeps the row so old links say
-- "revoked" instead of "not found".
-- Who: only Amr (course_is_admin: owner, with the authenticator when he has one) issues, renews and revokes, through
-- the functions below. Each person reads their own certificates. No one writes the table directly.
-- It's a course certificate, never a license (the wording lives on the pages). Safe to run more than once.

create table if not exists public.certificates (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^ACQ-[0-9A-F]{5}-[0-9A-F]{5}$'),
  user_id uuid references auth.users(id) on delete set null,
  course text not null default 'acq' check (course in ('acq')),
  name text not null check (char_length(btrim(name)) between 2 and 80),
  issued_on date not null default ((now() at time zone 'Africa/Cairo')::date),
  valid_until date not null,
  renewed_on date,
  revoked_at timestamptz,
  revoked_note text check (revoked_note is null or char_length(revoked_note) <= 200),
  issued_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (valid_until > issued_on)
);
create unique index if not exists certificates_one_active on public.certificates (user_id, course) where revoked_at is null;
alter table public.certificates enable row level security;
revoke all on public.certificates from anon, authenticated;
-- Only the columns a person's own card needs: never Amr's revoke note or who issued it
revoke select on public.certificates from authenticated;
grant select (id, code, user_id, course, name, issued_on, valid_until, renewed_on, revoked_at, created_at) on public.certificates to authenticated;
drop policy if exists "certificates read" on public.certificates;
create policy "certificates read" on public.certificates for select to authenticated
  using (user_id = auth.uid() or coalesce(public.is_tracker_admin(), false));

-- Where someone stands against Lesson 20.1 (Amr only). Facts only; Amr decides.
--   checkpoints: Modules 1 to 19 checkpoints passed (of 19); final_exam: the Module 20 exam passed; capstone: the
--   capstone deal file approved; calls_40: scored calls of 40+ with no part below 3 (role-plays or real calls, in
--   the Review center or Call scoring); best_call: the highest of those.
create or replace function public.certificate_readiness(p_user uuid)
returns table(checkpoints integer, final_exam boolean, capstone boolean, calls_40 integer, best_call integer)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.course_is_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query
  with ok as (
    select (h.score ->> 'total')::integer total from public.hub_uploads h
     where h.user_id = p_user and h.course in ('acq', 'calls') and h.status = 'approved' and h.score is not null
       and jsonb_typeof(h.score -> 'cats') = 'array' and jsonb_array_length(h.score -> 'cats') = 10
       and (h.score ->> 'total') ~ '^[0-9]+$' and (h.score ->> 'total')::integer >= 40
       and not exists (select 1 from jsonb_array_elements_text(h.score -> 'cats') c where c !~ '^[0-9]+$' or c::integer < 3))
  select
    (select count(distinct a.module_id)::integer from public.course_attempts a
      where a.user_id = p_user and a.passed and a.score >= 85 and a.finished_at is not null and not a.abandoned
        and a.item_id ~ '^([1-9]|1[0-9])\.checkpoint$' and a.module_id = 'm' || split_part(a.item_id, '.', 1)),
    exists (select 1 from public.course_attempts a where a.user_id = p_user and a.module_id = 'm20' and a.item_id = '20.checkpoint'
             and a.passed and a.score >= 85 and a.finished_at is not null and not a.abandoned),
    exists (select 1 from public.course_submissions s where s.user_id = p_user and s.module_id = 'm20' and s.item_id = '20.assignment' and s.status = 'approved'),
    (select count(*)::integer from ok),
    (select max(total) from ok);
end $$;
revoke all on function public.certificate_readiness(uuid) from public, anon;
grant execute on function public.certificate_readiness(uuid) to authenticated;

-- Amr's page: everyone with the Acquisitions course, where they stand, and their current certificate
create or replace function public.certificate_people()
returns table(user_id uuid, name text, checkpoints integer, final_exam boolean, capstone boolean, calls_40 integer, best_call integer,
              cert_id bigint, code text, cert_name text, issued_on date, valid_until date, renewed_on date)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.course_is_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query
  select m.user_id, m.name, r.checkpoints, r.final_exam, r.capstone, r.calls_40, r.best_call,
         c.id, c.code, c.name, c.issued_on, c.valid_until, c.renewed_on
    from public.members m
    cross join lateral public.certificate_readiness(m.user_id) r
    left join public.certificates c on c.user_id = m.user_id and c.course = 'acq' and c.revoked_at is null
   where m.active and m.user_id is not null and to_jsonb(m.access) ? 'course'
   order by (c.id is null), r.final_exam desc, r.checkpoints desc, m.name;
end $$;
revoke all on function public.certificate_people() from public, anon;
grant execute on function public.certificate_people() to authenticated;

-- Every certificate ever issued, newest first (Amr), including revoked ones and people no longer on the team
create or replace function public.certificate_list()
returns table(id bigint, code text, user_id uuid, name text, issued_on date, valid_until date, renewed_on date, revoked_at timestamptz, revoked_note text)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.course_is_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query select c.id, c.code, c.user_id, c.name, c.issued_on, c.valid_until, c.renewed_on, c.revoked_at, c.revoked_note
    from public.certificates c order by c.created_at desc;
end $$;
revoke all on function public.certificate_list() from public, anon;
grant execute on function public.certificate_list() to authenticated;

-- Issue: one current certificate per person per course
create or replace function public.certificate_issue(p_user uuid, p_name text)
returns text language plpgsql security definer set search_path = '' as $$
declare v_code text; v_today date := (now() at time zone 'Africa/Cairo')::date; v_name text := btrim(regexp_replace(coalesce(p_name, ''), '\s+', ' ', 'g'));
begin
  if not coalesce(public.course_is_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  if char_length(v_name) not between 2 and 80 then raise exception 'Type the name as it should appear (2 to 80 letters).' using errcode = '22023'; end if;
  if not exists (select 1 from public.members m where m.user_id = p_user and m.active and to_jsonb(m.access) ? 'course') then
    raise exception 'Pick someone with the Acquisitions course.' using errcode = '22023';
  end if;
  if exists (select 1 from public.certificates c where c.user_id = p_user and c.course = 'acq' and c.revoked_at is null) then
    raise exception 'They already have a current certificate. Renew it instead.' using errcode = '22023';
  end if;
  loop
    v_code := 'ACQ-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 5)) || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 5));
    exit when not exists (select 1 from public.certificates c where c.code = v_code);
  end loop;
  insert into public.certificates (code, user_id, course, name, issued_on, valid_until)
  values (v_code, p_user, 'acq', v_name, v_today, (v_today + interval '1 year')::date);
  perform public.notify(p_user, 'review_done', 'You’re certified: Acquisitions Playbook', 'Your course certificate is ready. Open it to see or share it.', '/cert/?c=' || v_code);
  return v_code;
end $$;
revoke all on function public.certificate_issue(uuid, text) from public, anon;
grant execute on function public.certificate_issue(uuid, text) to authenticated;

-- Renew: a year from today, or from the current end date if that's later
create or replace function public.certificate_renew(p_id bigint)
returns date language plpgsql security definer set search_path = '' as $$
declare v_today date := (now() at time zone 'Africa/Cairo')::date; v_until date; v_user uuid; v_code text;
begin
  if not coalesce(public.course_is_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  update public.certificates c set valid_until = (greatest(c.valid_until, v_today) + interval '1 year')::date, renewed_on = v_today
   where c.id = p_id and c.revoked_at is null returning c.valid_until, c.user_id, c.code into v_until, v_user, v_code;
  if v_until is null then raise exception 'That certificate isn''t current.' using errcode = '22023'; end if;
  perform public.notify(v_user, 'review_done', 'Your certificate was renewed', 'Valid until ' || to_char(v_until, 'FMMonth FMDD, YYYY') || '.', '/cert/?c=' || v_code);
  return v_until;
end $$;
revoke all on function public.certificate_renew(bigint) from public, anon;
grant execute on function public.certificate_renew(bigint) to authenticated;

-- Revoke: kept on record, the public page then says it was revoked
create or replace function public.certificate_revoke(p_id bigint, p_note text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not coalesce(public.course_is_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  update public.certificates c set revoked_at = now(), revoked_note = nullif(left(btrim(coalesce(p_note, '')), 200), '')
   where c.id = p_id and c.revoked_at is null;
  if not found then raise exception 'That certificate isn''t current.' using errcode = '22023'; end if;
end $$;
revoke all on function public.certificate_revoke(bigint, text) from public, anon;
grant execute on function public.certificate_revoke(bigint, text) to authenticated;

-- The public check (anyone, signed in or not): only what's printed on the certificate, for one exact code
create or replace function public.certificate_check(p_code text)
returns table(code text, name text, course text, issued_on date, valid_until date, renewed_on date, status text)
language sql stable security definer set search_path = '' as $$
  select c.code, case when c.revoked_at is null then c.name end, 'Acquisitions Playbook'::text,
         case when c.revoked_at is null then c.issued_on end, case when c.revoked_at is null then c.valid_until end,
         case when c.revoked_at is null then c.renewed_on end,
         case when c.revoked_at is not null then 'revoked'
              when c.valid_until < (now() at time zone 'Africa/Cairo')::date then 'renewal_due'
              else 'current' end
    from public.certificates c
   where c.code = upper(btrim(coalesce(p_code, '')))
$$;
revoke all on function public.certificate_check(text) from public;
grant execute on function public.certificate_check(text) to anon, authenticated;
