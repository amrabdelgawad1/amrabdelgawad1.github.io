  using (coalesce(public.is_tracker_admin(), false)) with check (coalesce(public.is_tracker_admin(), false));

-- Entries: clean the state notes, keep the old wording when it changes, stamp the times
create or replace function public.library_entries_check()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.state_notes := coalesce((select jsonb_agg(jsonb_build_object('state', upper(left(btrim(x ->> 'state'), 2)), 'note', left(btrim(x ->> 'note'), 400)))
                                 from jsonb_array_elements(new.state_notes) x
                                where coalesce(btrim(x ->> 'state'), '') ~* '^[a-z]{2}$' and coalesce(btrim(x ->> 'note'), '') <> ''), '[]'::jsonb);
  new.parts := coalesce((select array_agg(distinct p order by p) from unnest(new.parts) p), '{}');
  new.updated_at := now();
  if tg_op = 'INSERT' then
    new.version := 1; new.created_at := now();
  else
    new.created_at := old.created_at;
    if new.body is distinct from old.body then
      insert into public.library_versions (entry_id, version, body) values (old.id, old.version, old.body) on conflict do nothing;
      new.version := old.version + 1;
    else
      new.version := old.version;
    end if;
  end if;
  return new;
end $$;
revoke all on function public.library_entries_check() from public, anon, authenticated;
drop trigger if exists library_entries_check on public.library_entries;
create trigger library_entries_check before insert or update on public.library_entries for each row execute function public.library_entries_check();

-- Reads and taps: always now, always yourself
create or replace function public.library_stamp()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.user_id := auth.uid();
  if tg_table_name = 'library_reads' then new.read_at := now(); else new.at := now(); end if;
  return new;
end $$;
revoke all on function public.library_stamp() from public, anon, authenticated;
drop trigger if exists library_reads_stamp on public.library_reads;
create trigger library_reads_stamp before insert or update on public.library_reads for each row execute function public.library_stamp();
drop trigger if exists library_heard_stamp on public.library_heard;
create trigger library_heard_stamp before insert on public.library_heard for each row execute function public.library_stamp();

-- Examples: only a real call everyone agreed to record, scored 45 or more
create or replace function public.library_examples_check()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.hub_uploads h where h.id = new.upload_id and h.course = 'calls' and h.real_call and h.consent
                   and h.score is not null and (h.score ->> 'total')::int >= 45) then
    raise exception 'Only a real call scored 45 or more can be an example.' using errcode = '22023';
  end if;
  new.created_at := now();
  return new;
end $$;
revoke all on function public.library_examples_check() from public, anon, authenticated;
drop trigger if exists library_examples_check on public.library_examples;
create trigger library_examples_check before insert on public.library_examples for each row execute function public.library_examples_check();

-- How often each objection was heard (the whole team, counts only) in the last 7, 30 or 90 days
create or replace function public.library_heard_counts(p_days integer default 30)
returns table(entry_id bigint, heard integer, mine integer)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.library_can_read() then raise exception 'Not allowed' using errcode = '42501'; end if;
  if p_days not in (7, 30, 90) then raise exception 'Pick 7, 30 or 90 days' using errcode = '22023'; end if;
  return query
  select h.entry_id, count(*)::integer, count(*) filter (where h.user_id = auth.uid())::integer
    from public.library_heard h where h.at > now() - make_interval(days => p_days)
   group by h.entry_id;
end $$;
revoke all on function public.library_heard_counts(integer) from public, anon;
grant execute on function public.library_heard_counts(integer) to authenticated;

-- Example recordings for the library: what the page needs to play them, nothing about the seller
create or replace function public.library_example_calls()
returns table(entry_id bigint, upload_id uuid, path text, title text, total integer, rep text, created_at timestamptz)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.library_can_read() then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query
  select e.entry_id, h.id, h.path, h.title, (h.score ->> 'total')::integer, split_part(coalesce(public.notify_name(h.user_id), ''), ' ', 1), h.created_at
    from public.library_examples e join public.hub_uploads h on h.id = e.upload_id
   order by (h.score ->> 'total')::integer desc, h.created_at desc;
end $$;
revoke all on function public.library_example_calls() from public, anon;
grant execute on function public.library_example_calls() to authenticated;

-- The calling team may play example recordings (only files attached as examples)
create or replace function public.library_is_example(p_path text)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.library_can_read() and exists (select 1 from public.library_examples e join public.hub_uploads h on h.id = e.upload_id where h.path = p_path)
$$;
revoke all on function public.library_is_example(text) from public, anon;
grant execute on function public.library_is_example(text) to authenticated;
drop policy if exists "hub-uploads examples read" on storage.objects;
create policy "hub-uploads examples read" on storage.objects for select to authenticated
  using (bucket_id = 'hub-uploads' and public.library_is_example(name));
