-- Phase 1: the call counter. One row per tap while clocked in: dial, conversation, offer or appointment.
-- No phone numbers, names or notes: only who, when, what kind, and which shift. The end-of-shift numbers are
-- filled from these (the rep can still change them before sending). Later rounds add lead_id and client_id.
-- Rules: an active team member adds and reads their own taps, and can undo a tap within 10 minutes. Amr reads
-- everyone's through portal_calls(). Safe to run more than once.
create table if not exists public.call_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  at timestamptz not null default now(),
  kind text not null check (kind in ('dial', 'conversation', 'offer', 'appointment')),
  shift_started_at timestamptz not null
);
create index if not exists call_events_user_shift on public.call_events (user_id, shift_started_at);
create index if not exists call_events_at on public.call_events (at desc);
alter table public.call_events enable row level security;
revoke all on public.call_events from anon, authenticated;
grant select, insert, delete on public.call_events to authenticated;

drop policy if exists "call_events own add" on public.call_events;
create policy "call_events own add" on public.call_events for insert to authenticated
  with check (user_id = auth.uid() and at > now() - interval '5 minutes' and at < now() + interval '5 minutes'
              and shift_started_at > now() - interval '24 hours' and shift_started_at <= now() + interval '5 minutes'
              and exists (select 1 from public.members m where m.user_id = auth.uid() and m.active));
drop policy if exists "call_events own read" on public.call_events;
create policy "call_events own read" on public.call_events for select to authenticated using (user_id = auth.uid());
drop policy if exists "call_events own undo" on public.call_events;
create policy "call_events own undo" on public.call_events for delete to authenticated using (user_id = auth.uid() and at > now() - interval '10 minutes');

-- Amr: everyone's taps per person and day (counts only)
create or replace function public.portal_calls(p_days integer default 7)
returns table(day date, user_id uuid, name text, dials integer, conversations integer, offers integer, appointments integer)
language plpgsql stable security definer set search_path = '' as $$
begin
  if not coalesce(public.is_tracker_admin(), false) then raise exception 'Not allowed' using errcode = '42501'; end if;
  return query
  select (c.at at time zone 'America/New_York')::date, c.user_id, coalesce(m.name, 'Someone'),
         count(*) filter (where c.kind = 'dial')::integer, count(*) filter (where c.kind = 'conversation')::integer,
         count(*) filter (where c.kind = 'offer')::integer, count(*) filter (where c.kind = 'appointment')::integer
    from public.call_events c left join public.members m on m.user_id = c.user_id
   where c.at > now() - make_interval(days => greatest(1, least(p_days, 90)))
   group by 1, 2, 3 order by 1 desc, 4 desc;
end $$;
revoke all on function public.portal_calls(integer) from public, anon;
grant execute on function public.portal_calls(integer) to authenticated;
